#!/usr/bin/env python3
"""Generate docs/admin_modules.rst from tools/modules.json."""
from __future__ import annotations
import argparse
import json
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
METADATA = ROOT / "tools" / "modules.json"
OUTPUT = ROOT / "docs" / "admin_modules.rst"
def load_modules() -> list[dict[str, object]]:
 data = json.loads(METADATA.read_text(encoding="utf-8"))
 modules = data.get("modules")
 if not isinstance(modules, list):
  raise SystemExit("modules.json: missing modules array")
 return modules
def render(modules: list[dict[str, object]]) -> str:
 lines = [
  "Admin Modules",
  "=============",
  "",
  "Mesh exposes a small administration plane below ``mesh admin``. The",
  "commands are read-mostly, separately testable and share the same",
  "repository, graph, monitor and object-store contracts as the core.",
  "",
  "This file is generated by ``tools/module_docs.py`` from",
  "``tools/modules.json``. Edit the metadata, then regenerate the page.",
  "",
  ".. list-table::",
  "   :header-rows: 1",
  "   :widths: 18 24 26 32",
  "",
  "   * - Module",
  "     - File",
  "     - Command",
  "     - Purpose",
 ]
 for module in modules:
  lines.extend([
   f"   * - ``{module['name']}``",
   f"     - ``{module['file']}``",
   f"     - ``{module['command']}``",
   f"     - {module['summary']}",
  ])
 lines.extend([
  "",
  "Tools",
  "-----",
  "",
  "The ``tools`` directory contains eight standard-library scripts that",
  "inventory, check, graph, scaffold, test, document, measure and clean the",
  "additional C modules. They do not need a package manager or a virtual",
  "environment.",
  "",
  ".. code-block:: sh",
  "",
  "   python3 tools/module_inventory.py",
  "   python3 tools/module_check.py",
  "   python3 tools/module_graph.py",
  "   python3 tools/module_scaffold.py reports --summary \"report exporter\"",
  "   python3 tools/module_test.py",
  "   python3 tools/module_docs.py --check",
  "   python3 tools/module_metrics.py",
  "   python3 tools/module_clean.py --apply",
  "",
  "Safety",
  "------",
  "",
  "``mesh admin gc`` is a dry run by default. ``--apply`` requires a non-empty",
  "history and the repository lock. ``mesh admin verify`` reads every object",
  "referenced by a reachable manifest; a missing or modified object is a",
  "failure, not a warning.",
  "",
  "For implementation boundaries and safe operating mitigations, see",
  ":doc:`limitations`.",
  "",
 ])
 return "\n".join(lines)
def main() -> int:
 parser = argparse.ArgumentParser(description="Generate admin module docs.")
 parser.add_argument("--write", action="store_true", help="write the page")
 parser.add_argument("--check", action="store_true", help="verify the page")
 args = parser.parse_args()
 content = render(load_modules())
 if args.check:
  if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
   print(f"{OUTPUT} is stale", file=sys.stderr)
   return 1
  print(f"{OUTPUT} is current")
  return 0
 if args.write:
  OUTPUT.write_text(content, encoding="utf-8")
  print(f"wrote {OUTPUT}")
  return 0
 print(content, end="")
 return 0
if __name__ == "__main__":
 raise SystemExit(main())
